def configure_physical_plausibility_logging(level: int = logging.INFO, log_file: Optional[str | Path] = None) -> logging.Logger:
    """Configure module logging in a reusable, idempotent way."""

    logger.setLevel(level)
    if not any(isinstance(h, logging.StreamHandler) and getattr(h, "_lrt_console", False) for h in logger.handlers):
        handler = logging.StreamHandler()
        handler._lrt_console = True  # type: ignore[attr-defined]
        handler.setFormatter(logging.Formatter("%(asctime)s %(levelname)s %(name)s - %(message)s"))
        logger.addHandler(handler)
    if log_file is not None:
        log_path = Path(log_file)
        log_path.parent.mkdir(parents=True, exist_ok=True)
        file_handler = logging.FileHandler(log_path, encoding="utf-8")
        file_handler.setFormatter(logging.Formatter("%(asctime)s %(levelname)s %(name)s - %(message)s"))
        logger.addHandler(file_handler)
    return logger


def validate_physical_plausibility_config(config: PhysicalPlausibilityConfig) -> None:
    """Fail fast on ambiguous physical-plausibility thresholds."""

    if not (0 <= config.ehull_stable_threshold <= config.ehull_metastable_threshold <= config.ehull_high_metastability_threshold):
        raise ValueError("ehull thresholds must be ordered: stable <= metastable <= high_metastability.")
    if not (0 <= config.known_synthesized_bonus <= 1):
        raise ValueError("known_synthesized_bonus must be between 0 and 1.")
    if not (0 <= config.missing_data_penalty <= 1):
        raise ValueError("missing_data_penalty must be between 0 and 1.")
    if not (0 <= config.pair_dubious_score_threshold <= 1):
        raise ValueError("pair_dubious_score_threshold must be between 0 and 1.")


def physical_plausibility_manifest(config: PhysicalPlausibilityConfig) -> Dict[str, Any]:
    """Return stable metadata for downstream run manifests."""

    return {
        "schema_version": PHYSICAL_PLAUSIBILITY_SCHEMA_VERSION,
        "created_at_utc": datetime.now(timezone.utc).isoformat(),
        "config": config.to_dict(),
        "material_labels": [label.value for label in MaterialPhysicalLabel],
        "pair_labels": [label.value for label in PairPhysicalLabel],
        "output_columns": list(PHYSICAL_PLAUSIBILITY_OUTPUT_COLUMNS),
    }


def validate_physical_output_schema(df: Any, require_all_columns: bool = True) -> None:
    """Validate expected physical-plausibility output columns."""

    if pd is None:
        raise RuntimeError("pandas is required for validate_physical_output_schema().")
    missing = [col for col in PHYSICAL_PLAUSIBILITY_OUTPUT_COLUMNS if col not in df.columns]
    if require_all_columns and missing:
        raise ValueError(f"Physical plausibility output is missing required columns: {missing}")


class PhysicalPlausibilityAnnotator:
    """
    Adds physical plausibility metadata to material and pair records.

    Parameters
    ----------
    material_lookup:
        Mapping from JID to material records. Records may be dictionaries,
        MaterialRecord-like objects with `.raw` / `.features`, pandas rows, or
        mixed objects. The annotator extracts fields defensively.
    config:
        Thresholds and aliases.
    known_synthesized_map:
        Optional external mapping from JID to known synthesized status. This is
        useful because known synthesized status is often absent from JARVIS raw
        fields.
    """

    def __init__(
        self,
        material_lookup: Optional[Mapping[str, Any]] = None,
        config: Optional[PhysicalPlausibilityConfig] = None,
        known_synthesized_map: Optional[Mapping[str, Any]] = None,
    ) -> None:
        self.material_lookup: Dict[str, Any] = dict(material_lookup or {})
        self.config = config or PhysicalPlausibilityConfig()
        validate_physical_plausibility_config(self.config)
        self.known_synthesized_map: Dict[str, Optional[bool]] = {
            str(k): safe_bool(v) for k, v in dict(known_synthesized_map or {}).items()
        }
        self._annotation_cache: Dict[Optional[str], MaterialPhysicalAnnotation] = {}

    @classmethod
    def from_material_store(
        cls,
        store: Any,
        config: Optional[PhysicalPlausibilityConfig] = None,
        known_synthesized_map: Optional[Mapping[str, Any]] = None,
    ) -> "PhysicalPlausibilityAnnotator":
        """
        Construct an annotator from a MaterialStore-like object.

        The method intentionally uses duck typing to avoid coupling this module
        tightly to one material_store.py implementation.
        """

        lookup: Dict[str, Any] = {}

        if hasattr(store, "ensure_universe"):
            try:
                store.ensure_universe()
            except Exception as exc:
                logger.warning("Could not eagerly build material-store universe for plausibility lookup: %s", exc)

        # Common case: a store exposes a dataframe-like `universe_df` or `df`.
        for attr in ("universe_df", "materials_df", "df", "material_df"):
            obj = getattr(store, attr, None)
            if pd is not None and obj is not None and hasattr(obj, "iterrows") and "jid" in obj.columns:
                for _, row in obj.iterrows():
                    jid = row.get("jid")
                    if jid is not None:
                        lookup[str(jid)] = row.to_dict()
                break

        # Fallback: known dict-like lookup fields.
        for attr in ("records", "material_records", "record_by_jid", "materials_by_jid", "lookup"):
            obj = getattr(store, attr, None)
            if isinstance(obj, Mapping):
                for jid, record in obj.items():
                    lookup[str(jid)] = record

        # Last resort: if the store exposes resolve(), keep a thin proxy rather
        # than enumerating everything. annotate_material handles callable lookup.
        if not lookup and hasattr(store, "resolve"):
            lookup["__STORE_PROXY__"] = store

        return cls(lookup, config=config, known_synthesized_map=known_synthesized_map)

    @classmethod
    def from_dataframe(
        cls,
        material_df: Any,
        config: Optional[PhysicalPlausibilityConfig] = None,
        known_synthesized_map: Optional[Mapping[str, Any]] = None,
    ) -> "PhysicalPlausibilityAnnotator":
        """Construct from a dataframe with a jid column."""

        if pd is None:
            raise RuntimeError("pandas is required for from_dataframe().")
        if "jid" not in material_df.columns:
            raise ValueError("material_df must contain a 'jid' column.")
        lookup = {str(row["jid"]): row.to_dict() for _, row in material_df.iterrows()}
        return cls(lookup, config=config, known_synthesized_map=known_synthesized_map)

    @classmethod
    def from_known_synthesized_csv(
        cls,
        material_lookup: Optional[Mapping[str, Any]],
        csv_path: str | Path,
        config: Optional[PhysicalPlausibilityConfig] = None,
        jid_column: str = "jid",
        status_column: str = "known_synthesized",
    ) -> "PhysicalPlausibilityAnnotator":
        """Construct with an external known-synthesized CSV map."""

        if pd is None:
            raise RuntimeError("pandas is required for from_known_synthesized_csv().")
        df = pd.read_csv(csv_path)
        if jid_column not in df.columns or status_column not in df.columns:
            raise ValueError(f"CSV must contain columns '{jid_column}' and '{status_column}'.")
        mapping = {str(row[jid_column]): row[status_column] for _, row in df.iterrows()}
        return cls(material_lookup=material_lookup, config=config, known_synthesized_map=mapping)

    # ------------------------------------------------------------------
    # Material annotation
    # ------------------------------------------------------------------

    def annotate_material(self, jid: Optional[str], material: Optional[Any] = None) -> MaterialPhysicalAnnotation:
        """Return physical plausibility annotation for one material."""

        jid_key = str(jid) if jid is not None else None
        if material is None and jid_key in self._annotation_cache:
            return self._annotation_cache[jid_key]

        record = material if material is not None else self._get_material_record(jid_key)
        flattened = self._flatten_material_record(record)

        formation_energy = safe_float(first_present(flattened, self.config.formation_energy_aliases))
        energy_above_hull = safe_float(first_present(flattened, self.config.energy_above_hull_aliases))

        known_synthesized = None
        if jid_key in self.known_synthesized_map:
            known_synthesized = self.known_synthesized_map.get(jid_key)
        if known_synthesized is None:
            known_synthesized = safe_bool(first_present(flattened, self.config.known_synthesized_aliases))

        annotation = self._classify_material(
            jid=jid_key,
            formation_energy=formation_energy,
            energy_above_hull=energy_above_hull,
            known_synthesized=known_synthesized,
        )
        if material is None:
            self._annotation_cache[jid_key] = annotation
        return annotation

    def _classify_material(
        self,
        jid: Optional[str],
        formation_energy: Optional[float],
        energy_above_hull: Optional[float],
        known_synthesized: Optional[bool],
    ) -> MaterialPhysicalAnnotation:
        flags: List[str] = []
        evidence: List[str] = []
        available = 0
        possible = 3

        if formation_energy is not None:
            available += 1
            evidence.append(f"formation_energy={formation_energy:.6g}")
            if self.config.formation_energy_positive_dubious and formation_energy > self.config.positive_formation_energy_flag_threshold:
                flags.append("positive_formation_energy")
        else:
            flags.append("missing_formation_energy")

        if energy_above_hull is not None:
            available += 1
            evidence.append(f"energy_above_hull={energy_above_hull:.6g}")
        else:
            flags.append("missing_energy_above_hull")

        if known_synthesized is not None:
            available += 1
            evidence.append(f"known_synthesized={known_synthesized}")
        else:
            flags.append("missing_known_synthesized_status")

        data_completeness = available / possible

        if known_synthesized is True and energy_above_hull is None:
            label = MaterialPhysicalLabel.STABLE_OR_KNOWN.value
            score = 0.85
            flags.append("known_synthesized_no_ehull")
        elif energy_above_hull is None:
            label = MaterialPhysicalLabel.INSUFFICIENT_DATA.value
            score = 0.50 - self.config.missing_data_penalty
        elif energy_above_hull <= self.config.ehull_stable_threshold:
            label = MaterialPhysicalLabel.STABLE_OR_KNOWN.value
            score = 0.95
        elif energy_above_hull <= self.config.ehull_metastable_threshold:
            label = MaterialPhysicalLabel.METASTABLE_OR_UNCERTAIN.value
            score = 0.75
            flags.append("metastable_energy_above_hull")
        elif energy_above_hull <= self.config.ehull_high_metastability_threshold:
            label = MaterialPhysicalLabel.HIGH_METASTABILITY_WARNING.value
            score = 0.55
            flags.append("high_metastability_energy_above_hull")
        else:
            label = MaterialPhysicalLabel.PHYSICALLY_DUBIOUS.value
            score = 0.25
            flags.append("high_energy_above_hull")

        if known_synthesized is True:
            score = min(1.0, score + self.config.known_synthesized_bonus)
            flags.append("known_synthesized_support")
            if label == MaterialPhysicalLabel.PHYSICALLY_DUBIOUS.value:
                # Keep the warning but avoid implying the material is impossible.
                label = MaterialPhysicalLabel.HIGH_METASTABILITY_WARNING.value
                flags.append("known_synthesized_overrides_dubious_label_to_warning")

        if known_synthesized is False:
            flags.append("no_known_synthesis_support")

        if formation_energy is not None and formation_energy > self.config.positive_formation_energy_flag_threshold:
            score = min(score, 0.60)
            if label == MaterialPhysicalLabel.STABLE_OR_KNOWN.value and known_synthesized is not True:
                label = MaterialPhysicalLabel.METASTABLE_OR_UNCERTAIN.value

        score = max(0.0, min(1.0, score))
        return MaterialPhysicalAnnotation(
            jid=jid,
            formation_energy=formation_energy,
            energy_above_hull=energy_above_hull,
            known_synthesized=known_synthesized,
            label=label,
            score=score,
            flags=tuple(dict.fromkeys(flags)),
            evidence=tuple(evidence),
            data_completeness=data_completeness,
        )

    # ------------------------------------------------------------------
    # Pair annotation
    # ------------------------------------------------------------------

    def annotate_pair(
        self,
        jid_a: Optional[str],
        jid_b: Optional[str],
        material_a: Optional[Any] = None,
        material_b: Optional[Any] = None,
    ) -> PairPhysicalAnnotation:
        """Return pair-level physical plausibility annotation."""

        ann_a = self.annotate_material(jid_a, material=material_a)
        ann_b = self.annotate_material(jid_b, material=material_b)
        label = self._combine_pair_label(ann_a, ann_b)
        score = min(ann_a.score, ann_b.score)
        completeness = (ann_a.data_completeness + ann_b.data_completeness) / 2.0

        flags: List[str] = []
        flags.extend(f"a:{flag}" for flag in ann_a.flags)
        flags.extend(f"b:{flag}" for flag in ann_b.flags)

        if label == PairPhysicalLabel.TOPOLOGY_ONLY_WARNING.value:
            flags.append("structurally_interesting_but_physical_warning")
        elif label == PairPhysicalLabel.PHYSICALLY_DUBIOUS_PAIR.value:
            flags.append("pair_physically_dubious")
        elif label == PairPhysicalLabel.INSUFFICIENT_DATA.value:
            flags.append("pair_insufficient_physical_data")

        evidence = [
            f"a_label={ann_a.label}",
            f"b_label={ann_b.label}",
            *[f"a:{item}" for item in ann_a.evidence],
            *[f"b:{item}" for item in ann_b.evidence],
        ]

        return PairPhysicalAnnotation(
            jid_a=str(jid_a) if jid_a is not None else None,
            jid_b=str(jid_b) if jid_b is not None else None,
            label=label,
            score=max(0.0, min(1.0, score)),
            flags=tuple(dict.fromkeys(flags)),
            evidence=tuple(evidence),
            data_completeness=max(0.0, min(1.0, completeness)),
            material_a=ann_a,
            material_b=ann_b,
        )

    def _combine_pair_label(
        self,
        ann_a: MaterialPhysicalAnnotation,
        ann_b: MaterialPhysicalAnnotation,
    ) -> str:
        labels = {ann_a.label, ann_b.label}
        severities = [_material_severity(ann_a.label), _material_severity(ann_b.label)]

        if MaterialPhysicalLabel.PHYSICALLY_DUBIOUS.value in labels:
            if labels == {MaterialPhysicalLabel.PHYSICALLY_DUBIOUS.value}:
                return PairPhysicalLabel.PHYSICALLY_DUBIOUS_PAIR.value
            return PairPhysicalLabel.TOPOLOGY_ONLY_WARNING.value

        if MaterialPhysicalLabel.INSUFFICIENT_DATA.value in labels:
            if max(severities) >= 3:
                return PairPhysicalLabel.TOPOLOGY_ONLY_WARNING.value
            return PairPhysicalLabel.INSUFFICIENT_DATA.value

        if MaterialPhysicalLabel.HIGH_METASTABILITY_WARNING.value in labels:
            return PairPhysicalLabel.TOPOLOGY_ONLY_WARNING.value

        if MaterialPhysicalLabel.METASTABLE_OR_UNCERTAIN.value in labels:
            return PairPhysicalLabel.PLAUSIBLE_BUT_UNCERTAIN.value

        return PairPhysicalLabel.PLAUSIBLE_PAIR.value

    # ------------------------------------------------------------------
    # Dataframe annotation
    # ------------------------------------------------------------------

    def annotate_pair_dataframe(
        self,
        pair_df: Any,
        jid_a_col: Optional[str] = None,
        jid_b_col: Optional[str] = None,
        preserve_rank_columns: bool = True,
    ) -> Any:
        """
        Add physical plausibility columns to a pair/retrieval dataframe.

        The method preserves all existing columns and row order. It does not sort,
        filter, or alter retrieval ranking columns.
        """

        if pd is None:
            raise RuntimeError("pandas is required for annotate_pair_dataframe().")
        if pair_df is None:
            raise ValueError("pair_df cannot be None.")

        df = pair_df.copy()
        original_order = list(df.index)
        original_rank_values = {}
        if preserve_rank_columns:
            for col in ("retrieval_rank", "rank", "framework_rank"):
                if col in df.columns:
                    original_rank_values[col] = df[col].copy()

        resolved_a_col, resolved_b_col = self._resolve_pair_jid_columns(df, jid_a_col, jid_b_col)
        annotations: List[PairPhysicalAnnotation] = []

        for _, row in df.iterrows():
            jid_a = row.get(resolved_a_col) if resolved_a_col else None
            jid_b = row.get(resolved_b_col) if resolved_b_col else None
            annotations.append(self.annotate_pair(jid_a, jid_b))

        df["formation_energy_a"] = [ann.material_a.formation_energy for ann in annotations]
        df["formation_energy_b"] = [ann.material_b.formation_energy for ann in annotations]
        df["energy_above_hull_a"] = [ann.material_a.energy_above_hull for ann in annotations]
        df["energy_above_hull_b"] = [ann.material_b.energy_above_hull for ann in annotations]
        df["known_synthesized_a"] = [ann.material_a.known_synthesized for ann in annotations]
        df["known_synthesized_b"] = [ann.material_b.known_synthesized for ann in annotations]
        df["physical_plausibility_label_a"] = [ann.material_a.label for ann in annotations]
        df["physical_plausibility_label_b"] = [ann.material_b.label for ann in annotations]
        df["physical_plausibility_score_a"] = [ann.material_a.score for ann in annotations]
        df["physical_plausibility_score_b"] = [ann.material_b.score for ann in annotations]
        df["physical_plausibility_flags_a"] = [_as_serialized_flags(ann.material_a.flags) for ann in annotations]
        df["physical_plausibility_flags_b"] = [_as_serialized_flags(ann.material_b.flags) for ann in annotations]
        df["pair_physical_plausibility_label"] = [ann.label for ann in annotations]
        df["pair_physical_plausibility_score"] = [ann.score for ann in annotations]
        df["physical_data_completeness"] = [ann.data_completeness for ann in annotations]
        df["physical_plausibility_flags"] = [_as_serialized_flags(ann.flags) for ann in annotations]
        df["physical_plausibility_evidence"] = [_as_serialized_flags(ann.evidence) for ann in annotations]
        df["physical_plausibility_summary"] = [self._pair_summary(ann) for ann in annotations]
        df["physical_plausibility_schema_version"] = PHYSICAL_PLAUSIBILITY_SCHEMA_VERSION
        validate_physical_output_schema(df, require_all_columns=True)

        # Defensive rank/order preservation checks. If these trip, integration code
        # has probably sorted elsewhere, because this method does not.
        if list(df.index) != original_order:
            raise RuntimeError("annotate_pair_dataframe changed dataframe row order unexpectedly.")
        for col, values in original_rank_values.items():
            if not df[col].equals(values):
                raise RuntimeError(f"annotate_pair_dataframe changed rank column '{col}' unexpectedly.")

        return df

    def soft_filter_pair_dataframe(
        self,
        annotated_pair_df: Any,
        allowed_labels: Optional[Sequence[str]] = None,
    ) -> Any:
        """
        Return a soft-filtered *view* of an already annotated dataframe.

        This is intentionally separate from annotate_pair_dataframe so Phase 2 can
        produce physically less-dubious views without changing core retrieval.
        """

        if pd is None:
            raise RuntimeError("pandas is required for soft_filter_pair_dataframe().")
        if "pair_physical_plausibility_label" not in annotated_pair_df.columns:
            raise ValueError("Input dataframe must first be annotated with annotate_pair_dataframe().")
        allowed = set(
            allowed_labels
            or [
                PairPhysicalLabel.PLAUSIBLE_PAIR.value,
                PairPhysicalLabel.PLAUSIBLE_BUT_UNCERTAIN.value,
                PairPhysicalLabel.INSUFFICIENT_DATA.value,
            ]
        )
        return annotated_pair_df[annotated_pair_df["pair_physical_plausibility_label"].isin(allowed)].copy()

    def summarize_pair_dataframe(self, annotated_pair_df: Any, top_k: int = 50) -> Dict[str, Any]:
        """Produce compact diagnostics for reports and summary JSON files."""

        if pd is None:
            raise RuntimeError("pandas is required for summarize_pair_dataframe().")
        if "pair_physical_plausibility_label" not in annotated_pair_df.columns:
            raise ValueError("Input dataframe must first be annotated with annotate_pair_dataframe().")

        df = annotated_pair_df.copy()
        top_df = df.head(top_k)
        label_counts = df["pair_physical_plausibility_label"].value_counts(dropna=False).to_dict()
        top_label_counts = top_df["pair_physical_plausibility_label"].value_counts(dropna=False).to_dict()

        def frac(label: str, frame: Any) -> float:
            if len(frame) == 0:
                return 0.0
            return float((frame["pair_physical_plausibility_label"] == label).mean())

        return {
            "schema_version": PHYSICAL_PLAUSIBILITY_SCHEMA_VERSION,
            "row_count": int(len(df)),
            "top_k": int(top_k),
            "physical_plausibility_label_counts": {str(k): int(v) for k, v in label_counts.items()},
            "top_k_physical_plausibility_label_counts": {str(k): int(v) for k, v in top_label_counts.items()},
            "top_k_physically_dubious_fraction": frac(PairPhysicalLabel.PHYSICALLY_DUBIOUS_PAIR.value, top_df),
            "top_k_topology_only_warning_fraction": frac(PairPhysicalLabel.TOPOLOGY_ONLY_WARNING.value, top_df),
            "top_k_insufficient_data_fraction": frac(PairPhysicalLabel.INSUFFICIENT_DATA.value, top_df),
            "mean_pair_physical_plausibility_score": float(df["pair_physical_plausibility_score"].mean()) if len(df) else 0.0,
            "mean_physical_data_completeness": float(df["physical_data_completeness"].mean()) if len(df) else 0.0,
        }

    def get_manifest(self) -> Dict[str, Any]:
        """Return physical-plausibility metadata suitable for run manifests."""

        return physical_plausibility_manifest(self.config)

    def write_manifest(self, path: str | Path) -> None:
        """Write physical-plausibility metadata to JSON."""

        out = Path(path)
        out.parent.mkdir(parents=True, exist_ok=True)
        with open(out, "w", encoding="utf-8") as f:
            json.dump(self.get_manifest(), f, indent=2, sort_keys=True)

