"""
Physical plausibility assessment utilities.

Overview
--------
This module provides post-processing utilities for assessing whether candidate
materials are physically plausible based on inexpensive structural and
chemical evidence already generated by the Phase 1 pipeline.

Design goals
------------
* Preserve the evidence-driven architecture.
* Avoid modifying retrieval, ranking or role assignment logic.
* Provide transparent annotations explaining why a candidate appears
  physically plausible or warrants caution.
* Remain computationally inexpensive so it can be applied to large batches.

Developer notes
---------------
This module forms part of the "cheap context first" workflow. It should not
introduce expensive calculations or external simulations. New plausibility
checks should be deterministic, documented, and justified so that future
contributors can understand both their intent and limitations.

"""
from __future__ import annotations

"""
physical_plausibility.py

Physical plausibility annotation utilities for the Cheap Context First framework.

Purpose
-------
Adds conservative physical plausibility metadata to retrieval results without
changing similarity scores, rankings or role assignments. The module is intended
to improve interpretability rather than predictive performance.

Responsibilities
----------------
* Annotate individual materials using formation energy, energy above hull and
  synthesis evidence where available.
* Produce pair-level plausibility assessments for retrieved neighbours.
* Preserve deterministic behaviour and avoid altering retrieval outputs.
* Gracefully handle missing physical data.

Dependencies
------------
External:
* pandas (optional, for dataframe annotation)

Internal:
* Material store object exposing material metadata.

Public entry points
-------------------
* PhysicalPlausibilityAnnotator
* PhysicalPlausibilityConfig

Maintenance notes
-----------------
This module is designed to be largely self-contained. Thresholds should only be
changed after validation because downstream reports assume stable semantics.
"""

