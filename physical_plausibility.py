def annotate_pair_dataframe(
    pair_df: Any,
    material_lookup: Optional[Mapping[str, Any]] = None,
    config: Optional[PhysicalPlausibilityConfig] = None,
    known_synthesized_map: Optional[Mapping[str, Any]] = None,
    jid_a_col: Optional[str] = None,
    jid_b_col: Optional[str] = None,
) -> Any:
    """Convenience wrapper around PhysicalPlausibilityAnnotator."""

    annotator = PhysicalPlausibilityAnnotator(
        material_lookup=material_lookup,
        config=config,
        known_synthesized_map=known_synthesized_map,
    )
    return annotator.annotate_pair_dataframe(pair_df, jid_a_col=jid_a_col, jid_b_col=jid_b_col)


def classify_material_physical_plausibility(
    material: Mapping[str, Any],
    config: Optional[PhysicalPlausibilityConfig] = None,
) -> MaterialPhysicalAnnotation:
    """Classify one material dictionary without constructing a full lookup."""

    annotator = PhysicalPlausibilityAnnotator(config=config)
    jid = material.get("jid") if isinstance(material, Mapping) else None
    return annotator.annotate_material(jid=str(jid) if jid is not None else None, material=material)


def classify_pair_physical_plausibility(
    material_a: Mapping[str, Any],
    material_b: Mapping[str, Any],
    config: Optional[PhysicalPlausibilityConfig] = None,
) -> PairPhysicalAnnotation:
    """Classify one pair of material dictionaries."""

    annotator = PhysicalPlausibilityAnnotator(config=config)
    jid_a = material_a.get("jid") if isinstance(material_a, Mapping) else None
    jid_b = material_b.get("jid") if isinstance(material_b, Mapping) else None
    return annotator.annotate_pair(
        jid_a=str(jid_a) if jid_a is not None else None,
        jid_b=str(jid_b) if jid_b is not None else None,
        material_a=material_a,
        material_b=material_b,
    )


