class MaterialPhysicalLabel(str, Enum):
    """Stable string labels for material-level physical plausibility."""

    STABLE_OR_KNOWN = "stable_or_known"
    METASTABLE_OR_UNCERTAIN = "metastable_or_uncertain"
    HIGH_METASTABILITY_WARNING = "high_metastability_warning"
    PHYSICALLY_DUBIOUS = "physically_dubious"
    INSUFFICIENT_DATA = "insufficient_data"


class PairPhysicalLabel(str, Enum):
    """Stable string labels for pair-level physical plausibility."""

    PLAUSIBLE_PAIR = "plausible_pair"
    PLAUSIBLE_BUT_UNCERTAIN = "plausible_but_uncertain"
    TOPOLOGY_ONLY_WARNING = "topology_only_warning"
    PHYSICALLY_DUBIOUS_PAIR = "physically_dubious_pair"
    INSUFFICIENT_DATA = "insufficient_data"


@dataclass(frozen=True)
class PhysicalPlausibilityConfig:
    """
    Configuration for Phase 2 physical plausibility annotation.

    Thresholds are in eV/atom where the source data is eV/atom. The defaults are
    intentionally soft and should be treated as annotation rules, not scientific
    proof of synthesizability.
    """

    ehull_stable_threshold: float = 0.025
    ehull_metastable_threshold: float = 0.100
    ehull_high_metastability_threshold: float = 0.200
    formation_energy_positive_dubious: bool = True
    positive_formation_energy_flag_threshold: float = 0.0
    known_synthesized_bonus: float = 0.25
    missing_data_penalty: float = 0.15
    soft_filter_enabled: bool = False
    pair_dubious_score_threshold: float = 0.40

    formation_energy_aliases: Tuple[str, ...] = (
        "formation_energy",
        "formation_energy_peratom",
        "form_energy_peratom",
        "formation_energy_per_atom",
        "formation_energy_pa",
    )
    energy_above_hull_aliases: Tuple[str, ...] = (
        "energy_above_hull",
        "ehull",
        "e_above_hull",
        "e_above_hull_per_atom",
        "energy_above_hull_peratom",
    )
    known_synthesized_aliases: Tuple[str, ...] = (
        "known_synthesized",
        "is_synthesized",
        "synthesized",
        "experimentally_synthesized",
        "icsd",
        "icsd_id",
    )
    schema_version: str = PHYSICAL_PLAUSIBILITY_SCHEMA_VERSION

    def to_dict(self) -> Dict[str, Any]:
        payload = asdict(self)
        for key, value in list(payload.items()):
            if isinstance(value, tuple):
                payload[key] = list(value)
        return payload

    @classmethod
    def from_mapping(cls, payload: Mapping[str, Any]) -> "PhysicalPlausibilityConfig":
        data = dict(payload or {})
        for key in ("formation_energy_aliases", "energy_above_hull_aliases", "known_synthesized_aliases"):
            if key in data and not isinstance(data[key], tuple):
                data[key] = tuple(data[key])
        return cls(**data)

    @classmethod
    def from_json(cls, path: str | Path) -> "PhysicalPlausibilityConfig":
        with open(path, "r", encoding="utf-8") as f:
            return cls.from_mapping(json.load(f))

    def write_json(self, path: str | Path) -> None:
        out = Path(path)
        out.parent.mkdir(parents=True, exist_ok=True)
        with open(out, "w", encoding="utf-8") as f:
            json.dump(self.to_dict(), f, indent=2, sort_keys=True)


