    def _get_material_record(self, jid: Optional[str]) -> Optional[Any]:
        if jid is None:
            return None
        if jid in self.material_lookup:
            return self.material_lookup[jid]
        proxy = self.material_lookup.get("__STORE_PROXY__")
        if proxy is not None and hasattr(proxy, "resolve"):
            try:
                return proxy.resolve(jid, strict=False)
            except TypeError:
                try:
                    return proxy.resolve(jid)
                except Exception:
                    return None
            except Exception:
                return None
        return None

    def _flatten_material_record(self, record: Optional[Any]) -> Dict[str, Any]:
        if record is None:
            return {}

        flattened: Dict[str, Any] = {}

        if isinstance(record, Mapping):
            flattened.update(record)
        elif pd is not None and hasattr(record, "to_dict"):
            try:
                flattened.update(record.to_dict())
            except Exception:
                pass
        else:
            for attr in (
                "jid",
                "formula",
                "formation_energy",
                "formation_energy_peratom",
                "energy_above_hull",
                "ehull",
                "known_synthesized",
            ):
                if hasattr(record, attr):
                    flattened[attr] = getattr(record, attr)

        # MaterialRecord-like objects keep computed features and raw source fields.
        for attr in ("features", "raw"):
            obj = getattr(record, attr, None)
            if isinstance(obj, Mapping):
                flattened.update(obj)

        # Dict-style nested features/raw.
        for key in ("features", "raw"):
            obj = flattened.get(key)
            if isinstance(obj, Mapping):
                flattened.update(obj)

        return flattened

    def _resolve_pair_jid_columns(
        self,
        df: Any,
        jid_a_col: Optional[str],
        jid_b_col: Optional[str],
    ) -> Tuple[Optional[str], Optional[str]]:
        columns = set(df.columns)
        if jid_a_col and jid_b_col:
            if jid_a_col not in columns or jid_b_col not in columns:
                raise ValueError(f"Requested JID columns not found: {jid_a_col}, {jid_b_col}")
            return jid_a_col, jid_b_col

        candidate_pairs = [
            ("jid_a", "jid_b"),
            ("query_jid", "candidate_jid"),
            ("source_jid", "target_jid"),
            ("material_a_jid", "material_b_jid"),
        ]
        for left, right in candidate_pairs:
            if left in columns and right in columns:
                return left, right

        if "candidate_jid" in columns:
            return None, "candidate_jid"

        raise ValueError(
            "Could not infer pair JID columns. Provide jid_a_col/jid_b_col or include "
            "jid_a/jid_b or query_jid/candidate_jid columns."
        )

    def _pair_summary(self, ann: PairPhysicalAnnotation) -> str:
        return (
            f"pair_label={ann.label}; score={ann.score:.3f}; "
            f"data_completeness={ann.data_completeness:.3f}; "
            f"a={ann.material_a.label}; b={ann.material_b.label}"
        )


