def safe_float(value: Any) -> Optional[float]:
    """Convert a value to a finite float, returning None on missing/bad values."""

    try:
        if value is None:
            return None
        if isinstance(value, str):
            stripped = value.strip()
            if stripped == "" or stripped.lower() in {"nan", "none", "null", "na", "n/a"}:
                return None
            value = stripped
        number = float(value)
        if math.isnan(number) or math.isinf(number):
            return None
        return number
    except Exception:
        return None


def safe_bool(value: Any) -> Optional[bool]:
    """Parse common boolean/synthesis-status values."""

    if value is None:
        return None
    if isinstance(value, bool):
        return value
    if isinstance(value, (int, float)) and not isinstance(value, bool):
        if math.isnan(value) if isinstance(value, float) else False:
            return None
        return bool(value)
    if isinstance(value, str):
        stripped = value.strip().lower()
        if stripped in {"", "none", "null", "nan", "na", "n/a", "unknown"}:
            return None
        if stripped in {"true", "t", "yes", "y", "1", "synthesized", "known", "experimental", "experiment"}:
            return True
        if stripped in {"false", "f", "no", "n", "0", "not_synthesized", "not synthesized"}:
            return False
        # ICSD-like identifiers are often non-empty strings. Treat as evidence.
        return True
    return None


def first_present(mapping: Mapping[str, Any], aliases: Sequence[str]) -> Any:
    """Return the first non-empty value from a mapping using possible aliases."""

    for key in aliases:
        if key in mapping:
            value = mapping.get(key)
            if value is not None:
                if isinstance(value, str) and not value.strip():
                    continue
                return value
    return None


def _as_serialized_flags(flags: Iterable[str]) -> str:
    """Stable semicolon-delimited representation for CSV outputs."""

    unique = []
    seen = set()
    for flag in flags:
        if flag and flag not in seen:
            unique.append(flag)
            seen.add(flag)
    return ";".join(unique)


def _material_severity(label: str) -> int:
    """Higher is worse. Used for pair aggregation."""

    order = {
        MaterialPhysicalLabel.STABLE_OR_KNOWN.value: 0,
        MaterialPhysicalLabel.METASTABLE_OR_UNCERTAIN.value: 1,
        MaterialPhysicalLabel.HIGH_METASTABILITY_WARNING.value: 2,
        MaterialPhysicalLabel.PHYSICALLY_DUBIOUS.value: 3,
        MaterialPhysicalLabel.INSUFFICIENT_DATA.value: 2,
    }
    return order.get(str(label), 2)


